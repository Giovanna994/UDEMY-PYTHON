print(1234)

# Aspas simples
print('ASPAS SIMPLES')
print(1, 'ASPAS "SIMPLES"') # Utilização facilitada para não precisar o escape/r

# Aspas duplas
print("ASPAS DUPLAS")
print(2, "ASPAS 'DUPLAS'") # Utilização facilitada para não precisar o escape/r

# Escape
print("ESCAPE \"ESCAPE") # Pula o próximo caracter, o Python não vai ler as aspas

# r
print(r"ESCAPE \"ESCAPE\"")

# O 'Escape' e o 'r' não são muito utilizados por complicarem o código