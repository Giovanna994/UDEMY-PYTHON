# Tipos de int e float

# int = número inteiro
# O tipo int representa qualquer número, positivo ou negativo
# int sem sinal é considerado positivo

print (11) # int
print(-11) # int
print(0) # int

# float = número com ponto flutuante
# Representa qualquer número positivo ou negativo ocm ponto flutuante
# float sem sinal é considerado positivo

print(1.1) # o ponto sempre é usado para separar as casas decimais
print(1.1, 10.11) # a virgula é usada para separar os argumentos
print(0.0) #float
print(0.0, -1.5) #float

# A função type mostra o tipo que o Python inferiu ao valor

print(type('Teste')) # string
print(type(10)) # int
print(type(-10)) # int
print(type(1.0)) # float
print(type(-1.0)) # float