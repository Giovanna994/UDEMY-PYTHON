# Tipo de dado bool (boolean)

# Ao questionar algo em um programa, só existem duas respostas possiveis:
# sim (True) ou não (False)
# Existem varios operadores para questionar, dentre eles, o == é o operador lógico que questiona se um valor é igual a outro

print(10 == 10) # Sim = True (Verdadeiro)
print (10 == 9) # Não = False (Falso)
print (type(10 == 10)) # bool
print (type(10 == 9)) # bool
print(type(True)) # bool
print(type(False)) # bool